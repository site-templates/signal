    <p class="lead">A feature nobody hears about converts exactly nobody. The fastest marketing win most SaaS teams are sitting on isn't a campaign — it's the last three months of their own git history.</p>

    <p>We pulled the numbers on three teams who moved from "silent shipping" to publishing every release through a public changelog, an in-app widget, and an email digest. Same products, same features — the only variable was telling people.</p>

    <h2>The trial-conversion effect</h2>
    <p>Prospects in a trial read changelogs the way investors read commit activity: as a proxy for momentum. One team saw trial-to-paid conversion rise after nothing more than making their release cadence visible on a public page. Their sales team started linking the changelog in follow-up emails — "here's what shipped since we last talked" is the least salesy email a founder can send, and it works.</p>

    <h2>The adoption effect</h2>
    <p>Features announced only by email got a fraction of the first-week adoption of features that also badged in the app. The widget wins for an unexciting reason: it catches users <strong>at the moment they're already using the product</strong>, which is the only moment they can act on the news.</p>

    <h2>The churn effect</h2>
    <p>Churn interviews kept surfacing a line worth framing: "I didn't know it could do that." Every one of those is a release note that never got written. A visible, steady changelog is ambient reassurance — proof the product is alive, compounding weekly, worth staying subscribed to.</p>

    <h2>Treat it like a channel, because it is one</h2>
    <ol>
        <li>Give it a real URL on your domain, not a wiki page.</li>
        <li>Publish on a rhythm — cadence itself is the message.</li>
        <li>Deliver where your users already are: in-app, inbox, Slack.</li>
        <li>Measure it: reactions, reads, and the feature requests it generates.</li>
    </ol>

    <p>You already did the hard part — you shipped. The announcement is the cheap half of the value.</p>
